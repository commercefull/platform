/**
 * Order JSON serialization — flattened DTO used by toJSON().
 */

import type { OrderProps } from './orderTypes';

export function orderToJSON(props: OrderProps): Record<string, unknown> {
  return {
    orderId: props.orderId,
    orderNumber: props.orderNumber,
    customerId: props.customerId,
    basketId: props.basketId,
    storeId: props.storeId,
    channelId: props.channelId,
    createdByUserId: props.createdByUserId,
    marketId: props.marketId,
    localeCode: props.localeCode,
    contractingEntityId: props.contractingEntityId,
    orderSource: props.orderSource,
    status: props.status,
    paymentStatus: props.paymentStatus,
    fulfillmentStatus: props.fulfillmentStatus,
    currencyCode: props.currencyCode,
    catalogCurrencyCode: props.catalogCurrencyCode,
    displayedCurrencyCode: props.displayedCurrencyCode,
    settlementCurrencyCode: props.settlementCurrencyCode,
    accountingCurrencyCode: props.accountingCurrencyCode,
    exchangeRateSnapshot: props.exchangeRateSnapshot,
    versionSnapshot: props.versionSnapshot,
    decisionLog: props.decisionLog,
    subtotalCents: props.subtotal.cents,
    discountTotalCents: props.discountTotal.cents,
    taxTotalCents: props.taxTotal.cents,
    shippingTotalCents: props.shippingTotal.cents,
    handlingFeeCents: props.handlingFee.cents,
    totalAmountCents: props.totalAmount.cents,
    totalItems: props.totalItems,
    totalQuantity: props.totalQuantity,
    taxExempt: props.taxExempt,
    orderDate: props.orderDate.toISOString(),
    completedAt: props.completedAt?.toISOString(),
    cancelledAt: props.cancelledAt?.toISOString(),
    returnedAt: props.returnedAt?.toISOString(),
    shippingAddress: props.shippingAddress?.toJSON(),
    billingAddress: props.billingAddress?.toJSON(),
    customerEmail: props.customerEmail,
    customerPhone: props.customerPhone,
    customerName: props.customerName,
    customerNotes: props.customerNotes,
    adminNotes: props.adminNotes,
    estimatedDeliveryDate: props.estimatedDeliveryDate?.toISOString(),
    hasGiftWrapping: props.hasGiftWrapping,
    giftMessage: props.giftMessage,
    isGift: props.isGift,
    isSubscriptionOrder: props.isSubscriptionOrder,
    parentOrderId: props.parentOrderId,
    items: props.items.map(item => item.toJSON()),
    tags: props.tags,
    metadata: props.metadata,
    createdAt: props.createdAt.toISOString(),
    updatedAt: props.updatedAt.toISOString(),
    deletedAt: props.deletedAt?.toISOString(),
  };
}
